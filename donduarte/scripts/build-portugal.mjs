// Writes src/data/portugal.ts: mainland Portugal (Natural Earth 1:50m, via world-atlas) and the five wine
// regions of the wine map, projected into one SVG viewBox. The region outlines are schematic, drawn by
// hand in longitude/latitude around each DOC area, and clipped to the coastline in the map component.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/countries-50m.json"), "utf8"));
const pt = feature(topo, topo.objects.countries).features.find((f) => f.properties.name === "Portugal");
const polys = pt.geometry.type === "MultiPolygon" ? pt.geometry.coordinates : [pt.geometry.coordinates];
const mainland = polys.filter((p) => p[0].some(([lon]) => lon > -9.6 && lon < -6));

const [minLon, maxLon, minLat, maxLat] = [-9.6, -6.1, 36.9, 42.2];
const k = Math.cos((39.5 * Math.PI) / 180);
const W = 300;
const scale = W / ((maxLon - minLon) * k);
const H = Math.round((maxLat - minLat) * scale);
const xy = ([lon, lat]) => [((lon - minLon) * k * scale).toFixed(1), ((maxLat - lat) * scale).toFixed(1)];
const ring = (r) => "M" + r.map((p) => xy(p).join(" ")).join("L") + "Z";

const regions = {
  verde: { label: "Vinho Verde", ring: [[-8.95, 42.15], [-8.15, 42.15], [-7.85, 41.85], [-7.95, 41.35], [-8.2, 40.95], [-8.75, 40.92], [-9.0, 41.4]], at: [-8.45, 41.62] },
  douro: { label: "Douro", ring: [[-7.95, 41.3], [-7.55, 41.42], [-7.0, 41.38], [-6.75, 41.15], [-6.95, 40.95], [-7.45, 40.98], [-7.95, 41.05]], at: [-7.45, 41.18] },
  dao: { label: "Dão", ring: [[-8.25, 40.78], [-7.75, 40.88], [-7.48, 40.65], [-7.62, 40.33], [-8.15, 40.32], [-8.35, 40.55]], at: [-7.9, 40.6] },
  setubal: { label: "Palmela · Terras do Sado", ring: [[-9.25, 38.72], [-8.6, 38.8], [-8.35, 38.52], [-8.55, 38.15], [-8.85, 38.2], [-9.25, 38.42]], at: [-8.8, 38.5] },
  alentejo: { label: "Alentejo", ring: [[-8.3, 39.35], [-7.25, 39.45], [-6.95, 38.75], [-7.3, 37.95], [-8.15, 37.85], [-8.45, 38.35]], at: [-7.75, 38.62] },
};
const out = {
  viewBox: `0 0 ${W} ${H}`,
  outline: mainland.map((p) => ring(p[0])).join(""),
  regions: Object.fromEntries(Object.entries(regions).map(([id, r]) => [id, { label: r.label, d: ring(r.ring), x: +xy(r.at)[0], y: +xy(r.at)[1] }])),
  cities: { porto: xy([-8.61, 41.15]).map(Number), lisboa: xy([-9.14, 38.72]).map(Number) },
};
mkdirSync(new URL("../src/data/", import.meta.url), { recursive: true });
writeFileSync(new URL("../src/data/portugal.ts", import.meta.url), `// Generated by scripts/build-portugal.mjs. Do not edit.\nexport const PORTUGAL = ${JSON.stringify(out, null, 1)} as const;\n`);
console.log(out.viewBox, out.outline.length, "chars");

// Measures the cabin (light-line paths, star positions, anchor points) on the loaded M4 model and writes
// src/three/cabin-data.js. Needs the dev server:  node tools/serve.mjs 5173 &  then  node tools/bake-cabin.mjs
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
const require = createRequire(import.meta.url);
let chromium;
try { ({ chromium } = require('playwright')); } catch { ({ chromium } = require('/opt/node-tools/node_modules/playwright')); }
const base = process.argv[2] || 'http://127.0.0.1:5173';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 640, height: 360 } });
page.on('pageerror', (e) => console.log('pageerror', e.message));
await page.goto(`${base}/dev/model.html?m=car&cabin=live`);
await page.waitForFunction('window.__ready === true', null, { timeout: 120000 });
const data = await page.evaluate('window.__cabinData');
await browser.close();
const out = new URL('../src/three/cabin-data.js', import.meta.url).pathname;
writeFileSync(out, `// Generated by tools/bake-cabin.mjs from the M4 model. Do not edit by hand.\n// strips[].pts = x,y,z,nx,ny,nz per sample · stars = x,y,z per fibre · car coordinates in metres.\nexport default ${JSON.stringify(data)};\n`);
console.log(`cabin-data.js: ${data.strips.map((s) => `${s.id}:${s.pts.length / 6}`).join(' ')} · ${data.stars.length / 3} stars · anchors ${JSON.stringify(data.anchors)}`);
